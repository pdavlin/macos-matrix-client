#!/usr/bin/env python3
"""Convert Unicode's emoji-test.txt into the reaction picker's bundled emoji list.

MATRIX-111 (M2-B4, D-3). The reaction picker needs every emoji with its
CLDR English short name, grouped by category. Unicode publishes exactly that
in emoji-test.txt. This script keeps the part the picker uses and writes it
in a compact line format that `Models.EmojiCatalog.parse(_:)` reads.

Run it at development time only, when the Emoji version changes:

    curl -sSfL -o /tmp/emoji-test.txt https://unicode.org/Public/emoji/15.1/emoji-test.txt
    python3 -I scripts/generate-emoji-data.py /tmp/emoji-test.txt \
        MactrixLibrary/Sources/UI/Resources/Emoji.txt

Rules:
- Keep fully-qualified emoji only. That drops components, minimally-qualified,
  and unqualified forms.
- Drop every emoji that holds a skin-tone modifier (U+1F3FB to U+1F3FF). M2
  offers the default (yellow) emoji only.
- Keep the file's CLDR order, which is the order a picker shows.

Output format (UTF-8, one record per line, fields split by a tab):
    # comment line
    G<TAB>group name
    S<TAB>subgroup name
    <emoji><TAB><CLDR short name>
An emoji line belongs to the last G and S lines above it.
"""

import sys

SKIN_TONE_MODIFIERS = range(0x1F3FB, 0x1F3FF + 1)


def convert(source_lines):
    """Return the output lines for the lines of an emoji-test.txt file."""
    version = None
    output = []
    group = None
    subgroup = None
    pending_group = None
    pending_subgroup = None

    for raw in source_lines:
        line = raw.rstrip("\n")
        if line.startswith("# Version:"):
            version = line.split(":", 1)[1].strip()
            continue
        if line.startswith("# group:"):
            pending_group = line.split(":", 1)[1].strip()
            continue
        if line.startswith("# subgroup:"):
            pending_subgroup = line.split(":", 1)[1].strip()
            continue
        if not line or line.startswith("#"):
            continue

        fields, _, comment = line.partition("#")
        code_field, _, status = fields.partition(";")
        if status.strip() != "fully-qualified":
            continue

        code_points = [int(part, 16) for part in code_field.split()]
        if any(point in SKIN_TONE_MODIFIERS for point in code_points):
            continue

        # The comment is "<emoji> E<version> <name>".
        parts = comment.strip().split(" ", 2)
        if len(parts) != 3 or not parts[1].startswith("E"):
            raise ValueError(f"unexpected comment: {line}")
        name = parts[2].strip()
        emoji = "".join(chr(point) for point in code_points)

        if pending_group is not None and pending_group != group:
            group = pending_group
            output.append(f"G\t{group}")
        if pending_subgroup is not None and pending_subgroup != subgroup:
            subgroup = pending_subgroup
            output.append(f"S\t{subgroup}")
        output.append(f"{emoji}\t{name}")

    if version is None:
        raise ValueError("no '# Version:' line found")

    header = [
        f"# Emoji {version}, generated by scripts/generate-emoji-data.py from Unicode emoji-test.txt.",
        "# Fully-qualified emoji only, no skin-tone variants. Data (c) Unicode, Inc., Unicode License v3.",
        "# Do not edit by hand. Run the script again for a new Emoji version.",
    ]
    return header + output


def main(argv):
    if len(argv) != 3:
        print(f"usage: {argv[0]} <emoji-test.txt> <output>", file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as source:
        lines = convert(source)
    with open(argv[2], "w", encoding="utf-8") as target:
        target.write("\n".join(lines) + "\n")
    emoji_count = sum(1 for line in lines if not line.startswith(("# ", "G\t", "S\t")))
    print(f"wrote {emoji_count} emoji to {argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
